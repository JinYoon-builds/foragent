"""Acceptance (train-ci-first, statement 2).

The generated CI workflow gives lane PR CI a concurrency group that train
branches are not part of, so a new PR CI run for the same PR replaces its older
pending run.

Jin 11-08 (r1227, A): merge-train CI must not queue behind lane PR CI.

The workflow generator (`write_workflow`, the code behind `fa ci workflow`) writes
its workflows into a temporary repository; the committed copy in this repository
is read as well. Each workflow is read as GitHub reads it: the trigger decides
whether a run exists, a job's `if` decides whether the job runs, and the
workflow-level and job-level `concurrency` groups are evaluated with a GitHub
expression evaluator (tests/acceptance/gh_expressions.py) over the event's
`github` context.

"Not part of" is read strictly: no concurrency group a train-branch run joins is
a group some lane PR run can join, whatever PR numbers GitHub hands out. The
check therefore gives one lane PR the same PR number as the train PR; a group
built from the PR number alone puts both in one group.
"""

from pathlib import Path
import sys

import pytest
import yaml

ROOT = next(p for p in Path(__file__).resolve().parents if (p / "src/foragent").is_dir())
if str(ROOT / "tests/acceptance") not in sys.path:
    sys.path.append(str(ROOT / "tests/acceptance"))

from gh_expressions import condition, interpolate  # noqa: E402
from foragent.ci_workflow import write_workflow  # noqa: E402
from foragent.config import load_config  # noqa: E402
from foragent.merge_owner_batch import PREFIX  # noqa: E402

REPO = "owner/repo"
TRAIN_PR = 2753
TRAIN_BRANCH = f"{PREFIX}0123abcd-2"


def pull_request(number, branch, sha, *, base="main", run_id=555000111, action="synchronize"):
    """The `github` context of a same-repository pull_request run."""
    head_repo = {"full_name": REPO}
    return {
        "event_name": "pull_request", "workflow": None, "repository": REPO,
        "ref": f"refs/pull/{number}/merge", "ref_name": f"{number}/merge", "head_ref": branch,
        "base_ref": base, "sha": f"merge-{sha}", "run_id": run_id, "run_number": run_id % 1000,
        "run_attempt": 1, "actor": "foragent-bot", "triggering_actor": "foragent-bot",
        "event": {"action": action, "number": number, "pull_request": {
            "number": number, "head": {"ref": branch, "sha": sha, "repo": head_repo},
            "base": {"ref": base, "sha": "b" * 40, "repo": head_repo}}},
    }


def generated_workflows(tmp_path):
    root = tmp_path / "repo"
    root.mkdir()
    write_workflow(root, load_config(ROOT), warn=False)
    found = sorted((root / ".github/workflows").glob("*.y*ml"))
    assert found, "the generator wrote no workflow"
    return {path.name: yaml.safe_load(path.read_text(encoding="utf-8")) for path in found}


def committed_workflows():
    root = ROOT / ".github/workflows"
    rows = {}
    for path in sorted(root.glob("*.y*ml")):
        text = path.read_text(encoding="utf-8")
        if text.startswith("# Generated by fa ci workflow"):
            rows[path.name] = yaml.safe_load(text)
    assert rows, "no committed generated workflow"
    return rows


def triggered(workflow, github):
    on = workflow.get("on", workflow.get(True))
    if isinstance(on, str):
        on = {on: None}
    elif isinstance(on, list):
        on = {name: None for name in on}
    event = github["event_name"]
    if event not in (on or {}):
        return False
    rule = on[event] or {}
    base = github["base_ref"]
    if "branches" in rule and not any(_glob(pattern, base) for pattern in rule["branches"]):
        return False
    if "branches-ignore" in rule and any(_glob(pattern, base) for pattern in rule["branches-ignore"]):
        return False
    types = rule.get("types")
    return not types or github["event"]["action"] in types


def _glob(pattern, value):
    import fnmatch
    return fnmatch.fnmatchcase(value, pattern.replace("**", "*"))


def _group(concurrency, context):
    if concurrency is None:
        return None
    group = concurrency if isinstance(concurrency, str) else concurrency.get("group")
    return interpolate(group, context) or None


def run_groups(workflows, github):
    """Every concurrency group a run for this event joins, per workflow file."""
    groups = set()
    for name, workflow in workflows.items():
        if not triggered(workflow, github):
            continue
        context = {"github": dict(github, workflow=workflow.get("name") or name),
                   "inputs": {}, "vars": {}, "env": workflow.get("env") or {}}
        top = _group(workflow.get("concurrency"), context)
        if top:
            groups.add(("workflow", name, top.lower()))
        for job_id, job in (workflow.get("jobs") or {}).items():
            if not condition(job.get("if"), context):
                continue
            matrix = (job.get("strategy") or {}).get("matrix") or {}
            first = {key: (values[0] if isinstance(values, list) and values else values)
                     for key, values in matrix.items() if key not in {"include", "exclude"}}
            group = _group(job.get("concurrency"), dict(context, matrix=first, needs={}, strategy={}))
            if group:
                groups.add(("job", name, group.lower()))
    # GitHub concurrency groups are one namespace per repository, whatever their level.
    return {group for _, _, group in groups}


def lane_runs():
    return {
        "issue PR #2753 (same number as the train)": pull_request(TRAIN_PR, "foragent/issue-7", "1" * 40),
        "issue PR #42": pull_request(42, "foragent/issue-12", "2" * 40, run_id=555000222),
        "group PR #43": pull_request(43, "foragent/group-3-9", "3" * 40, run_id=555000333),
    }


@pytest.fixture(params=["generated", "committed"])
def workflows(request, tmp_path):
    return generated_workflows(tmp_path) if request.param == "generated" else committed_workflows()


def test_lane_pr_ci_concurrency_group_excludes_train_branches(workflows):
    lanes = {label: run_groups(workflows, github) for label, github in lane_runs().items()}
    for label, groups in lanes.items():
        assert groups, f"Lane PR CI ({label}) has a concurrency group"

    # A new push to the same lane PR joins the group of its older run, so the older pending run is replaced.
    again = pull_request(42, "foragent/issue-12", "4" * 40, run_id=555000999)
    assert run_groups(workflows, again) & lanes["issue PR #42"], (
        f"A new PR CI run for PR #42 shares a concurrency group with its older run: "
        f"{sorted(run_groups(workflows, again))} vs {sorted(lanes['issue PR #42'])}")

    # Different lane PRs do not replace each other's runs.
    assert not lanes["issue PR #42"] & lanes["group PR #43"], (
        f"Two lane PRs share a concurrency group: {sorted(lanes['issue PR #42'] & lanes['group PR #43'])}")

    # A train branch is never part of a lane PR CI group, even with an equal PR number.
    train = run_groups(workflows, pull_request(TRAIN_PR, TRAIN_BRANCH, "5" * 40, run_id=555000444))
    lane_groups = set().union(*lanes.values())
    shared = train & lane_groups
    assert not shared, (
        f"Train branch {TRAIN_BRANCH} (PR #{TRAIN_PR}) joins lane PR CI concurrency group(s) {sorted(shared)}; "
        f"train groups: {sorted(train)}, lane groups: {sorted(lane_groups)}")

    # Two pushes to one train branch stay outside every lane group too.
    later = run_groups(workflows, pull_request(TRAIN_PR, TRAIN_BRANCH, "6" * 40, run_id=555000555))
    assert not later & lane_groups
